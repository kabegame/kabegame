const layers = new Map<number, T>([
  [10, { origin: [700, 560, 30], angles: [0.3, 0.2, 0.35], scale: [1.25, 0.8, 1.1], parent: null }],
  [20, { origin: [-200, 120, 10], angles: [0.2, -0.1, 0.3], scale: [1.2, 0.9, 1.1], parent: 10 }],
  [21, { origin: [150, 100, -5], angles: [-0.15, 0.25, -0.2], scale: [0.9, 1.1, 1], parent: 10 }],
  [22, { origin: [-150, -130, 0], angles: [0.1, 0.2, 0.15], scale: [1, 1, 1], parent: 10 }],
]);

function matrices(object: number, role: "direct" | "effect" | "final", size: number[]) {
  const cache = new Map<number, Mat4>();
  const parts = groupMvpParts([800, 600], drawMatrixOf(10, layers, cache))!;
  const world = drawMatrixOf(object, layers, cache);
  return { parts, world, out: drawMatrices({ role }, world, size, parts.projection, parts) };
}

describe("组里图像层的矩阵照 WPE（p14c-gi）", () => {
  it("effect 的中间 pass（B20 的 kbm1，事件 118）：g_EffectModelMatrix = W · scale(w/2, h/2)、g_LayerModelMatrix = W（世界矩阵）", () => {
    const { out } = matrices(21, "effect", [140, 100]);
    expect(Array.from(out.effectModel!)).toEqual(B20_EFFECT.EffectModelMatrix);
    expect(Array.from(out.layerModel!)).toEqual(B20_EFFECT.LayerModelMatrix);
  });

  it("直接上屏（A20，事件 88）：g_ModelMatrix 是组内局部的（仿射乘法，glm 乘法不同）、g_ViewProjectionMatrix 是 P", () => {
    const { parts, world, out } = matrices(20, "direct", [120, 90]);
    expect(Array.from(out.model)).toEqual(A20.ModelMatrix);
    expect(Array.from(multiply(parts.inverse, world))).not.toEqual(A20.ModelMatrix);
    expect(Array.from(out.viewProjection).map((v) => v + 0)).toEqual(A20.ViewProjectionMatrix);
  });

  it.each([
    ["B20（两个探针 effect 的末 pass，事件 135）", 21, [140, 100], B20_FINAL],
    ["L20（预光照图层的末 pass，事件 173）", 22, [160, 120], L20_FINAL],
  ] as const)("%s：模型矩阵局部、视图投影 P，效果矩阵与 g_LayerModelMatrix 是世界矩阵", (_name, object, size, wpe) => {
    const { parts, world, out } = matrices(object, "final", [...size]);
    expect(Array.from(out.model)).toEqual(wpe.ModelMatrix);
    expect(Array.from(out.viewProjection).map((v) => v + 0)).toEqual(wpe.ViewProjectionMatrix);
    expect(Array.from(out.effectModel!)).toEqual(wpe.EffectModelMatrix);
    expect(Array.from(out.layerModel!)).toEqual(wpe.LayerModelMatrix);
    // 效果投影矩阵（有意不同）：WPE 是 P ⊗ W（漏了组的逆），我们取图层 MVP
    expect(Array.from(mulAffine(parts.projection, world))).toEqual(wpe.EffectModelViewProjectionMatrix);
    expect(out.effectModelViewProjection).toBe(out.modelViewProjection);
  });
});
